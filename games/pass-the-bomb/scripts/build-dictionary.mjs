// Regenerates server/dictionary.ts from a system word list:
//
//   node games/pass-the-bomb/scripts/build-dictionary.mjs [/usr/share/dict/american-english]
//
// Keeps lowercase a–z words of 3+ letters, which drops proper nouns ("Paris")
// and possessives ("cat's") for free. The list is front-coded: sorted, each
// word stored as how many letters it shares with the one before (one digit,
// capped at 9) plus the rest. "abandon, abandoned, abandons" → "0abandon7ed7s".
// About a third of the plain list (~220 KB, ~90 KB gzipped): the worker carries it.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const src = process.argv[2] ?? "/usr/share/dict/american-english";
const words = [...new Set(readFileSync(src, "utf8").split("\n").filter((w) => /^[a-z]{3,}$/.test(w)))].sort();

let packed = "";
let prev = "";
for (const w of words) {
  let p = 0;
  while (p < 9 && p < prev.length && w[p] === prev[p]) p++;
  packed += p + w.slice(p);
  prev = w;
}

const out = join(dirname(fileURLToPath(import.meta.url)), "../server/dictionary.ts");
writeFileSync(
  out,
  `// Generated by scripts/build-dictionary.mjs from ${src}. Don't edit by hand.\n` +
    `// ${words.length} words, front-coded (see the script). Server only: never import this from shared/ or client/.\n\n` +
    `export const WORD_COUNT = ${words.length};\n\n` +
    `export const PACKED = ${JSON.stringify(packed)};\n`,
);
console.log(`${words.length} words, ${packed.length} bytes packed → ${out}`);
