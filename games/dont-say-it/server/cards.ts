/** "Hide and seek" → "hide-and-seek". */
const slug = (target: string) => target.replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

/** Parses one line; throws on anything that isn't "target: a, b, c, d, e". */
export function parseCard(line: string): Card {
  const m = /^([^:]+):(.+)$/.exec(line);
  if (!m) throw new Error(`Not a card: "${line}". Expected "target: a, b, c, d, e".`);
  const target = m[1]!.trim();
  const forbidden = m[2]!.split(",").map((w) => w.trim()).filter(Boolean);
  if (!target || forbidden.length !== 5) throw new Error(`A card needs a target and five forbidden words: "${line}".`);
  return { id: slug(target), target, forbidden };
}

export const CARDS: readonly Card[] = LINES.map(parseCard);
